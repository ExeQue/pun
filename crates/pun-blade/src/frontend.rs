fn is_dom_event(name: &str) -> bool {
    DOM_EVENT_NAMES.binary_search(&name).is_ok()
}

pub(crate) fn is_frontend_event_style_at_name(name: &str) -> bool {
    is_dom_event(&name.to_ascii_lowercase())
}

pub(crate) fn is_html_event_attribute(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    lower.strip_prefix("on").is_some_and(is_dom_event)
}
